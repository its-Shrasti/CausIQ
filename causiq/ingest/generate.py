"""
CausIQ :: Synthetic Source Generator with Planted Ground Truth
==============================================================

WHY THIS EXISTS
---------------
A KPI root-cause engine can only be evaluated if you already know the answer.
Real enterprise data never comes with a label saying "the checkout release cost
you 3.5% of revenue". So we *plant* the causes, then check whether the engine
recovers them.

HOW GROUND TRUTH IS DEFINED
---------------------------
Revenue is generated by an explicit structural model:

    sessions   = base x seasonality x trend x PROD(shock session multipliers) x noise
    conversion = base x seasonality       x PROD(shock conversion multipliers) x noise
    aov        = base                     x PROD(shock aov multipliers)        x noise
    revenue    = sessions x conversion x aov

Each "shock" is a real-world event (a release, a stockout, a competitor promo).
Because the model is multiplicative, effects interact — so the contribution of
any single shock depends on which others are present. We therefore define the
ground-truth contribution of each shock as its **Shapley value** over the set
of all shocks: the average marginal effect across every possible subset.

Shapley values are the unique attribution that is efficient (they sum exactly
to the total effect), symmetric, and order-independent. With 5 shocks we
enumerate all 2^5 = 32 counterfactual worlds exhaustively — no approximation.

Critically, the noise arrays are drawn ONCE and held fixed across all 32
counterfactual runs. Toggling a shock therefore changes the outcome only
through that shock's own causal pathway, never through resampled randomness.

THE TRAP (deliberate)
---------------------
`in_stock_rate` and `competitor_price` reduce BOTH sessions and conversion.
So a large part of the session decline is *mediated*, not exogenous. An engine
that ranks drivers by correlation with revenue will blame the marketing budget
cut, because traffic tracks revenue almost perfectly. The causally correct
answer ranks the checkout release first and marketing last. Getting this wrong
costs Rs 60L/month in paid spend poured into a broken funnel.

Run:  python -m causiq.ingest.generate
"""

