# Deterministic base signal + fixed noise
# -----------------------------------------------------------------------------

@dataclass
class Panel:
    """Pre-computed deterministic signal and FIXED noise for one series.

    Fixing the noise is what makes counterfactual toggling valid: switching a
    shock off changes the outcome only through that shock's causal pathway.
    """
    dates: pd.DatetimeIndex
    region: str
    category: str
    channel: str
    base_sessions: np.ndarray
    base_cvr: np.ndarray
    base_aov: np.ndarray
    noise_sessions: np.ndarray = field(repr=False, default=None)
    noise_cvr: np.ndarray = field(repr=False, default=None)
    noise_aov: np.ndarray = field(repr=False, default=None)


def _seasonality(dates: pd.DatetimeIndex) -> np.ndarray:
    doy = dates.dayofyear.values.astype(float)
    dow = dates.dayofweek.values.astype(float)
    annual = 1.0 + 0.16 * np.sin(2 * np.pi * (doy - 45) / 365.25)
    weekly = 1.0 + 0.13 * np.sin(2 * np.pi * (dow - 1.5) / 7.0)
    # Festive lift: Indian festive season and EU Black Friday window
    festive = np.where((doy > 285) & (doy < 320), 1.22, 1.0)
    return annual * weekly * festive


def _cvr_seasonality(dates: pd.DatetimeIndex) -> np.ndarray:
    dow = dates.dayofweek.values.astype(float)
    return 1.0 + 0.06 * np.cos(2 * np.pi * (dow - 3.0) / 7.0)


def build_panels() -> list[Panel]:
    dates = pd.date_range(HISTORY_START, HISTORY_END, freq="D")
    n = len(dates)
    trend = np.linspace(1.0, 1.34, n)          # steady growth over 2.6 years
    seas = _seasonality(dates)
    cvr_seas = _cvr_seasonality(dates)

    panels: list[Panel] = []
    for region in REGIONS:
        for category in CATEGORIES:
            if category == "Wearables" and region not in WEARABLES_REGIONS:
                continue
            for channel in CHANNELS:
                # Calibrated so EU weekly net revenue lands near Rs 10.0 Cr
                scale = (
                    317_000
                    * REGION_SCALE[region]
                    * CATEGORY_MIX[category]
                    * CHANNEL_SPLIT[channel]
                )
                base_sessions = scale * trend * seas / 7.0
                base_cvr = np.full(n, CATEGORY_CVR[category]) * cvr_seas
                base_aov = np.full(n, CATEGORY_AOV[category])

                if category == "Wearables":
                    # Newly launched: nothing before launch date, plus a steep
                    # early-life ramp that no seasonal model can extrapolate.
                    live = (dates >= WEARABLES_LAUNCH).astype(float)
                    weeks_live = np.clip(
                        (dates - WEARABLES_LAUNCH).days.values / 7.0, 0, None
                    )
                    ramp = 1.0 - 0.55 * np.exp(-weeks_live / 3.2)
                    base_sessions = base_sessions * live * ramp
                    base_cvr = base_cvr * (0.72 + 0.28 * (1 - np.exp(-weeks_live / 4.0)))
                    # Early-life volatility. NOT a planted driver and therefore
                    # outside the Shapley set: a brand-new category swings hard
                    # week to week for reasons no model can attribute yet. This
                    # is what the sparse-history scenario has to resist
                    # over-explaining -- it looks like a 15% collapse, but with
                    # five weeks of history it is not distinguishable from the
                    # launch period's own noise.
                    dip = np.where(
                        (dates >= pd.Timestamp("2026-08-17"))
                        & (dates <= pd.Timestamp("2026-08-23")),
                        0.845, 1.0,
                    )
                    base_cvr = base_cvr * dip

                p = Panel(
                    dates=dates,
                    region=region,
                    category=category,
                    channel=channel,
                    base_sessions=base_sessions,
                    base_cvr=base_cvr,
                    base_aov=base_aov,
                )
                # Fixed noise, drawn once, reused across every counterfactual.
                # Calibrated to daily category-channel aggregates at this volume
                # (tens of thousands of sessions per cell), where relative noise
                # is genuinely low. Setting it higher would not make the demo
                # more honest, only less identifiable: the true session effects
                # here are 1-2%, and no estimator can separate those from 5%
                # daily noise on a three-week window.
                p.noise_sessions = RNG.normal(1.0, 0.012, n)
                p.noise_cvr = RNG.normal(1.0, 0.020, n)
                p.noise_aov = RNG.normal(1.0, 0.010, n)
                panels.append(p)
    return panels


# -----------------------------------------------------------------------------
# Counterfactual evaluation
# -----------------------------------------------------------------------------

def evaluate(panel: Panel, shocks: dict[str, Shock], active: set[str]) -> dict[str, np.ndarray]:
    """Evaluate one series under the subset `active` of shocks."""
    m_sess = np.ones(len(panel.dates))
    m_cvr = np.ones(len(panel.dates))
    m_aov = np.ones(len(panel.dates))

    for name in active:
        sh = shocks[name]
        a, b, c = sh.multipliers(panel.dates, panel.region, panel.category)
        m_sess *= a
        m_cvr *= b
        m_aov *= c

    sessions = panel.base_sessions * m_sess * panel.noise_sessions
    cvr = np.clip(panel.base_cvr * m_cvr * panel.noise_cvr, 1e-6, 0.65)
    aov = panel.base_aov * m_aov * panel.noise_aov
    orders = sessions * cvr
    revenue = orders * aov

    return {"sessions": sessions, "cvr": cvr, "aov": aov,
            "orders": orders, "revenue": revenue}


def window_revenue(panels: list[Panel], shocks: dict[str, Shock],
                   active: set[str], region: str,
                   start: pd.Timestamp, end: pd.Timestamp) -> float:
    """Total revenue in a region/date window under a given counterfactual."""
    total = 0.0
    for p in panels:
        if p.region != region:
            continue
        mask = (p.dates >= start) & (p.dates <= end)
        if not mask.any():
            continue
        total += float(evaluate(p, shocks, active)["revenue"][mask].sum())
    return total


def shapley_contributions(panels: list[Panel], shocks: dict[str, Shock],
                          region: str, start: pd.Timestamp,
                          end: pd.Timestamp) -> tuple[dict[str, float], float, float]:
    """Exact Shapley decomposition over all 2^5 counterfactual worlds.

    Returns (contribution_inr_by_shock, expected_revenue, actual_revenue).
    Contributions sum exactly to (actual - expected) by the efficiency axiom.
    """
    names = list(shocks.keys())
    k = len(names)

    # Pre-compute revenue for every subset — 32 evaluations, no approximation
    cache: dict[frozenset, float] = {}
    for r in range(k + 1):
        for combo in itertools.combinations(names, r):
            s = frozenset(combo)
            cache[s] = window_revenue(panels, shocks, set(s), region, start, end)

    contrib = {n: 0.0 for n in names}
    for n in names:
        others = [x for x in names if x != n]
        for r in range(len(others) + 1):
            weight = (math.factorial(r) * math.factorial(k - r - 1)) / math.factorial(k)
            for combo in itertools.combinations(others, r):
                s = frozenset(combo)
                contrib[n] += weight * (cache[s | {n}] - cache[s])

    expected = cache[frozenset()]
    actual = cache[frozenset(names)]
    return contrib, expected, actual


# -----------------------------------------------------------------------------
# Calibration: solve shock strengths to hit the target contributions
# -----------------------------------------------------------------------------

def calibrate(panels: list[Panel]) -> dict[str, Shock]:
    """Numerically solve for shock strengths hitting TARGET_CONTRIB_PCT.

    Because the model is multiplicative, a shock's Shapley contribution is not
    a simple function of its own strength — it depends on every other shock.
    So we solve the joint system rather than tuning constants by hand.
    """
    shocks = build_shocks()

    def residuals(x: np.ndarray) -> np.ndarray:
        for i, name in enumerate(SHOCK_NAMES):
            shocks[name].strength = float(abs(x[i]))
        contrib, expected, _ = shapley_contributions(
            panels, shocks, ANALYSIS_REGION, ANALYSIS_START, ANALYSIS_END
        )
        return np.array([
            100.0 * contrib[n] / expected - TARGET_CONTRIB_PCT[n]
            for n in SHOCK_NAMES
        ])

    x0 = np.array([0.14, 0.16, 0.10, 0.16, 0.09])
    sol = least_squares(residuals, x0, xtol=1e-8, ftol=1e-8, max_nfev=90)
    for i, name in enumerate(SHOCK_NAMES):
        shocks[name].strength = float(abs(sol.x[i]))
    return shocks


