@dataclass
class Shock:
    """A real-world event with a causal pathway onto sessions / cvr / aov.

    `strength` is solved numerically so the resulting Shapley contribution
    matches the target above. `w_*` weights split the effect across pathways
    and encode the mediation structure declared in the KPI contract's DAG.
    """
    name: str
    label: str
    start: pd.Timestamp
    end: pd.Timestamp
    regions: list[str]
    categories: list[str] | None      # None = all categories
    w_sessions: float = 0.0
    w_cvr: float = 0.0
    w_aov: float = 0.0
    sign: float = -1.0                # -1 depresses, +1 lifts
    strength: float = 0.05

    def active(self, dates: pd.DatetimeIndex, region: str, category: str) -> np.ndarray:
        if region not in self.regions:
            return np.zeros(len(dates), dtype=float)
        if self.categories is not None and category not in self.categories:
            return np.zeros(len(dates), dtype=float)
        return ((dates >= self.start) & (dates <= self.end)).astype(float)

    def multipliers(self, dates, region, category) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        a = self.active(dates, region, category)
        s = self.sign * self.strength
        return (
            1.0 + a * s * self.w_sessions,
            1.0 + a * s * self.w_cvr,
            1.0 + a * s * self.w_aov,
        )


