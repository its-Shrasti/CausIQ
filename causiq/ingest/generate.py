def emit_sources(panels: list[Panel], shocks: dict[str, Shock]) -> dict[str, pd.DataFrame]:
    """Materialise the four heterogeneous sources from the true world state."""
    rows_sales, rows_web, rows_ops = [], [], []
    all_active = set(shocks.keys())

    for p in panels:
        out = evaluate(p, shocks, all_active)
        sessions, cvr, aov = out["sessions"], out["cvr"], out["aov"]
        orders, revenue = out["orders"], out["revenue"]

        live = sessions > 0
        margin = CATEGORY_MARGIN[p.category]

        # --- discount depth, incl. the Accessories promo and a margin shift ---
        disc = np.full(len(p.dates), 0.06)
        promo = shocks["accessories_promo"]
        disc += 0.09 * promo.active(p.dates, p.region, p.category)
        # A genuine input-cost increase in EU from Aug 18 — the ambiguity that
        # makes the gross-margin movement un-attributable (abstention scenario)
        cogs_shift = np.where(
            (p.dates >= pd.Timestamp("2026-08-18")) & (p.region == "EU"), 0.028, 0.0
        )

        cogs = revenue * (1.0 - margin + cogs_shift)

        # --- paid marketing spend, an observed and controllable regressor ----
        # Paid is a minority of traffic; the planned cut is 30% of paid spend,
        # which is a far smaller share of total sessions. That gap is exactly
        # why the naive read over-credits marketing.
        mk = shocks["marketing_cut"]
        spend_base = float(np.mean(p.base_sessions)) * 41.0     # INR per session
        paid_spend = spend_base * (
            1.0 - 0.30 * mk.active(p.dates, p.region, p.category)
        ) * (1.0 + 0.05 * np.sin(np.arange(len(p.dates)) / 9.0))

        for i, d in enumerate(p.dates):
            if not live[i]:
                continue
            rows_sales.append({
                "date": d.date(),
                "region": p.region,
                "category": p.category,
                "channel": p.channel,
                "orders": round(float(orders[i]), 2),
                "net_revenue_inr": round(float(revenue[i]), 2),
                "discount_inr": round(float(revenue[i] * disc[i]), 2),
                "cogs_inr": round(float(cogs[i]), 2),
                "aov_inr": round(float(aov[i]), 2),
                "paid_spend_inr": round(float(paid_spend[i]), 2),
            })

        # --- web_events: HOURLY grain, must be rolled up before joining ---
        # Only the trailing 120 days are kept hourly (realistic retention).
        hourly_from = HISTORY_END - pd.Timedelta(days=120)
        for i, d in enumerate(p.dates):
            if not live[i]:
                continue
            if d < hourly_from:
                rows_web.append({
                    "datetime_hour": pd.Timestamp(d) + pd.Timedelta(hours=12),
                    "region": p.region, "channel": p.channel,
                    "device": "all", "category": p.category,
                    "sessions": round(float(sessions[i]), 2),
                    "checkout_starts": round(float(orders[i] * 2.35), 2),
                    "checkout_errors": 0.0,
                })
                continue

            # Distribute the day across 24 hours with a diurnal curve
            hours = np.arange(24)
            curve = 1.0 + 0.55 * np.sin(2 * np.pi * (hours - 8) / 24.0)
            curve = curve / curve.sum()
            # Checkout error rate: baseline ~0.4%, spikes in EU post-release
            ck = shocks["checkout_deploy"]
            err_rate = 0.004 + 0.061 * float(ck.active(
                pd.DatetimeIndex([d]), p.region, p.category)[0])
            for h in hours:
                s_h = float(sessions[i] * curve[h])
                starts = s_h * float(cvr[i]) * 2.35
                rows_web.append({
                    "datetime_hour": pd.Timestamp(d) + pd.Timedelta(hours=int(h)),
                    "region": p.region, "channel": p.channel,
                    "device": DEVICES[h % 2], "category": p.category,
                    "sessions": round(s_h, 2),
                    "checkout_starts": round(starts, 2),
                    "checkout_errors": round(starts * err_rate, 3),
                })

    # --- ops_inventory: WEEKLY grain against a DAILY KPI ---
    stock = shocks["stockout"]
    weeks = pd.date_range(pd.Timestamp("2024-06-03"), HISTORY_END, freq="W-MON")
    for wk in weeks:
        wk_days = pd.date_range(wk, wk + pd.Timedelta(days=6), freq="D")
        for region in REGIONS:
            for category in CATEGORIES:
                if category == "Wearables":
                    if region not in WEARABLES_REGIONS or wk < WEARABLES_LAUNCH:
                        continue
                a = stock.active(wk_days, region, category).mean()
                in_stock = 0.947 - 0.31 * a + float(RNG.normal(0, 0.012))
                rows_ops.append({
                    "iso_week": wk.date(),
                    "region": region,
                    "category": category,
                    "in_stock_rate": round(float(np.clip(in_stock, 0.30, 1.0)), 4),
                    "days_of_cover": round(float(np.clip(21 - 12 * a
                                                         + RNG.normal(0, 1.4), 1, 40)), 2),
                    "landed_cogs_index": round(float(
                        1.0 + (0.031 if (region == "EU" and wk
                                         >= pd.Timestamp("2026-08-17")) else 0.0)
                        + RNG.normal(0, 0.004)), 4),
                })

    sales = pd.DataFrame(rows_sales)
    web = pd.DataFrame(rows_web)
    ops = pd.DataFrame(rows_ops)

    # --- Planted data-quality defect: 18% of EU discount values null from Aug 20
    # This is what pushes the gross-margin case below the coverage threshold.
    defect_mask = (
        (pd.to_datetime(sales["date"]) >= pd.Timestamp("2026-08-20"))
        & (sales["region"] == "EU")
    )
    idx = sales.index[defect_mask]
    drop = RNG.choice(idx, size=int(len(idx) * 0.18), replace=False)
    sales.loc[drop, "discount_inr"] = np.nan

    # --- ops_inventory is STALE: last successful load was Mon 17 Aug.
    # At TODAY (27 Aug) that is 240h old against a 180h SLA -> breach.
    ops = ops[pd.to_datetime(ops["iso_week"]) <= pd.Timestamp("2026-08-17")]

    return {"wh_sales": sales, "web_events": web, "ops_inventory": ops}


